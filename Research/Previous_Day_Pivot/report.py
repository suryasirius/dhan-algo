import pandas as pd
import logging
from typing import Dict, Any
import config

class ReportGenerator:
    def __init__(self, metrics_df: pd.DataFrame, stats_results: Dict[str, Any], logger: logging.Logger):
        self.df = metrics_df
        self.stats = stats_results
        self.logger = logger

    def generate_csv(self) -> None:
        path = config.REPORTS_DIR / 'Previous_Day_Pivot_Research_Data.csv'
        self.df.to_csv(path)
        self.logger.info(f"CSV Report generated successfully at {path}")

    def generate_excel(self) -> None:
        path = config.REPORTS_DIR / 'Previous_Day_Pivot_Research_Data.xlsx'
        self.df.to_excel(path)
        self.logger.info(f"Excel Report generated successfully at {path}")

    def generate_html(self) -> None:
        path = config.REPORTS_DIR / 'Previous_Day_Pivot_Research_Data.html'
        self.df.to_html(path, classes='table table-striped table-bordered', index=True)
        self.logger.info(f"HTML Report generated successfully at {path}")

    def generate_summary_txt(self) -> None:
        path = config.REPORTS_DIR / 'Summary.txt'
        
        acc = self.stats['Overall_Trend_Prediction_Accuracy']
        should_use = "YES (with confirmation filters)" if acc > 50.0 else "NO (insufficient standalone edge)"
        
        summary_content = f"""
====================================================================
MARKET RESEARCH ENGINE: PREVIOUS DAY PIVOT POINT ANALYSIS
====================================================================

1. OVERALL PERFORMANCE METRICS
--------------------------------------------------------------------
Total Trading Days Analyzed         : {self.stats['Total_Days_Analyzed']}
Overall Trend Prediction Accuracy   : {acc:.2f}%
Confidence Score                    : {self.stats['Confidence_Score']:.2f} / 100
Best Performing Predictor           : {self.stats['Best_Predictor']}

2. MARKET CONDITIONS
--------------------------------------------------------------------
Best Market Condition               : {self.stats['Best_Market_Condition']}
Worst Market Condition              : {self.stats['Worst_Market_Condition']}
Trending Days Ratio                 : {self.stats['Trending_Days_Percent']:.2f}%
Range Days Ratio                    : {self.stats['Range_Days_Percent']:.2f}%

3. PIVOT BEHAVIORAL STATISTICS
--------------------------------------------------------------------
Pivot Respect Rate (0 Touches)      : {self.stats['Pivot_Respect_Percent']:.2f}%
Bullish Open Directional Accuracy   : {self.stats['Bullish_Accuracy_Percent']:.2f}%
Bearish Open Directional Accuracy   : {self.stats['Bearish_Accuracy_Percent']:.2f}%
False Breakout / Return Rate        : {self.stats['False_Breakout_Percent']:.2f}%
Breakout Probability                : {self.stats['Breakout_Percent']:.2f}%
Reversal Probability                : {self.stats['Reversal_Percent']:.2f}%

4. PRICE MOVEMENT DISTRIBUTION
--------------------------------------------------------------------
Average Move                        : {self.stats['Average_Move']:.2f}
Median Move                         : {self.stats['Median_Move']:.2f}
Mode Move                           : {self.stats['Mode_Move']:.2f}
Maximum Move                        : {self.stats['Maximum_Move']:.2f}
Minimum Move                        : {self.stats['Minimum_Move']:.2f}
Standard Deviation                  : {self.stats['Standard_Deviation']:.2f}
Variance                            : {self.stats['Variance']:.2f}

5. ARCHITECTURAL FINDINGS & RECOMMENDATIONS
--------------------------------------------------------------------
Pros:
- Provides objective, mathematical support and resistance boundaries.
- Excellent reference framework for identifying early morning sentiment bias.

Cons / Weaknesses:
- High vulnerability to whipsaws and false breakouts in range-bound environments.
- Lacks dynamic volume profile awareness.

Should Pivot be used?               : {should_use}
Should Pivot be combined?           : YES
Which indicator improves it?        : VWAP and Volume Profile / Order Flow
Which strategy benefits?            : Opening Range Breakout (ORB) and Mean Reversion
How can it be improved?             : Add volatility filters (ATR) and time-of-day execution windows.
What should AI learn?               : Pivot zones act as magnetic liquidity pools rather than hard impenetrable walls.

====================================================================
End of Research Report. Generated by Quant Research Engine.
====================================================================
        """
        
        with open(path, 'w', encoding='utf-8') as f:
            f.write(summary_content.strip())
            
        self.logger.info(f"Summary text report generated successfully at {path}")

    def generate_all(self) -> None:
        self.logger.info("Compiling final outputs and exporting reports...")
        self.generate_csv()
        self.generate_excel()
        self.generate_html()
        self.generate_summary_txt()
        self.logger.info("All research reports generated successfully.")