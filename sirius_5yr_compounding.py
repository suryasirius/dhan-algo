"""
Module: sirius_5yr_compounding.py
Description: Reruns the real 5-year Sirius result (already saved to
             sirius_5yr_trades.csv by sirius_5yr_backtest.py -- no need to
             refetch 5 years of Dhan data) with COMPOUNDING position sizing
             instead of a fixed 1-lot-per-trade size.

WHAT CHANGES: the original backtest always trades exactly 1 NSE lot per
signal, regardless of how much the account has grown. This version scales
the number of lots with the account's OWN accumulated profit: as capital
crosses each multiple of the Rs 25,000 starting base, position size steps
up by that same multiple. Example: if capital has grown to Rs 75,000 (3x
the start), the next trade uses 3x the normal lot count. Never drops below
1x, even in a drawdown, since a real order can't be smaller than 1 lot.

HONEST SIMPLIFICATIONS, stated plainly (not hidden):
  - Brokerage stays a flat Rs 40/trade regardless of lot count, same
    convention the original backtest used -- in reality, per-lot brokerage
    would likely scale up somewhat with bigger orders, so this is probably
    a small overstatement of compounded profit, not an understatement.
  - If capital ever hits zero or below, the account is marked WIPED OUT and
    no further trades are simulated from that point on (matches how a real
    account would actually stop, not silently go negative forever).
  - Uses the SAME real trade sequence (dates, directions, entry/exit
    points, pnl_pts) already generated by the real 5-year backtest -- only
    the position-sizing math changes, nothing about entry/exit logic.

Run (uses the already-saved CSV, no live Dhan connection needed):
    cd "C:\\dhan algo"
    python sirius_5yr_compounding.py
"""

import math
import numpy as np
import pandas as pd

import nifty_open_momentum_stoptrail_sweep as om

STARTING_CAPITAL = 25_000.0
BROKERAGE_PER_TRADE = 40.0
TRADES_CSV = "sirius_5yr_trades.csv"

# Realistic ceiling for the compounding model. Unconstrained compounding on
# the real 5-year trade sequence reaches tens of millions of lots per trade
# by year 5 -- pure fantasy, since Nifty options don't have that liquidity
# and NSE/SEBI impose real position limits well below that. 20x the base
# lot size is a much more defensible retail-scale ceiling, but it's a
# genuine judgment call, not a fact -- change MAX_LOT_MULTIPLIER if you want
# a different cap.
MAX_LOT_MULTIPLIER = 20

# The 6-month step-up model: instead of scaling with capital at all, just
# add one extra base lot every this many days, regardless of P&L. Much more
# conservative, and doesn't depend on the backtest's own profit being real.
STEP_UP_EVERY_DAYS = 182


def compute_lot_multiplier(capital: float, starting_capital: float = STARTING_CAPITAL,
                            max_multiplier: int = None) -> int:
    """How many multiples of the starting capital the account has grown to,
    floored, minimum 1x (never smaller than the original fixed size, and
    never a fraction of a lot). Optionally capped at max_multiplier to keep
    position size within a realistic ceiling."""
    if capital <= 0:
        return 0   # account is wiped out -- handled explicitly by the caller, not by sizing
    mult = max(1, math.floor(capital / starting_capital))
    if max_multiplier is not None:
        mult = min(mult, max_multiplier)
    return mult


def compute_stepup_multiplier(entry_date, start_date, step_every_days: int = STEP_UP_EVERY_DAYS) -> int:
    """Linear, profit-independent sizing: 1x to start, +1x for every
    step_every_days that have elapsed since the very first trade."""
    days_elapsed = (entry_date - start_date).days
    return 1 + max(0, days_elapsed // step_every_days)


def simulate_compounding(trades: pd.DataFrame, starting_capital: float = STARTING_CAPITAL,
                          max_multiplier: int = None) -> pd.DataFrame:
    """Walks the REAL trade sequence in chronological order, resizing each
    trade's lot count off the account's OWN accumulated capital at that
    point (not the original fixed-lot pnl already baked into the input).
    max_multiplier=None means uncapped (the original, unrealistic version);
    pass MAX_LOT_MULTIPLIER for the realistic capped version."""
    trades = trades.sort_values("entry_time").reset_index(drop=True)
    capital = starting_capital
    wiped_out = False
    rows = []
    for _, t in trades.iterrows():
        if wiped_out:
            rows.append({**t.to_dict(), "lots": 0, "rupee_pnl_compounded": 0.0,
                         "capital_after_compounded": capital, "skipped_wiped_out": True})
            continue

        multiplier = compute_lot_multiplier(capital, starting_capital, max_multiplier)
        base_lot = om.lot_size_for_date(pd.to_datetime(t["date"]).date())
        lots = base_lot * multiplier
        rupee_pnl = t["pnl_pts"] * lots - BROKERAGE_PER_TRADE
        capital += rupee_pnl
        if capital <= 0:
            wiped_out = True
        rows.append({**t.to_dict(), "lots": lots, "rupee_pnl_compounded": rupee_pnl,
                     "capital_after_compounded": capital, "skipped_wiped_out": False})
    return pd.DataFrame(rows)


def simulate_stepup(trades: pd.DataFrame, starting_capital: float = STARTING_CAPITAL,
                     step_every_days: int = STEP_UP_EVERY_DAYS) -> pd.DataFrame:
    """Walks the REAL trade sequence, sizing purely off elapsed TIME since
    the first trade (not off the account's own P&L at all) -- +1 base lot
    every step_every_days. Can still wipe out if losses are large enough,
    same safety handling as simulate_compounding."""
    trades = trades.sort_values("entry_time").reset_index(drop=True)
    if trades.empty:
        return trades.copy()
    start_date = pd.to_datetime(trades.iloc[0]["date"]).date()
    capital = starting_capital
    wiped_out = False
    rows = []
    for _, t in trades.iterrows():
        entry_date = pd.to_datetime(t["date"]).date()
        if wiped_out:
            rows.append({**t.to_dict(), "lots": 0, "rupee_pnl_stepup": 0.0,
                         "capital_after_stepup": capital, "skipped_wiped_out": True})
            continue
        multiplier = compute_stepup_multiplier(entry_date, start_date, step_every_days)
        base_lot = om.lot_size_for_date(entry_date)
        lots = base_lot * multiplier
        rupee_pnl = t["pnl_pts"] * lots - BROKERAGE_PER_TRADE
        capital += rupee_pnl
        if capital <= 0:
            wiped_out = True
        rows.append({**t.to_dict(), "lots": lots, "rupee_pnl_stepup": rupee_pnl,
                     "capital_after_stepup": capital, "skipped_wiped_out": False})
    return pd.DataFrame(rows)


def compute_metrics_from_series(rupee_pnl: pd.Series, starting_capital: float = STARTING_CAPITAL) -> dict:
    pnl = rupee_pnl.to_numpy()
    n = len(pnl)
    if n == 0:
        return {"n": 0, "win_pct": 0.0, "net_rs": 0.0, "max_dd_rs": 0.0, "sqn": 0.0}
    wins = pnl[pnl > 0]
    win_pct = 100.0 * len(wins) / n
    net_rs = pnl.sum()
    equity = starting_capital + np.cumsum(pnl)
    peak = np.maximum.accumulate(equity)
    dd = peak - equity
    max_dd_rs = dd.max()
    sqn = (pnl.mean() / pnl.std() * np.sqrt(n)) if n > 1 and pnl.std() > 0 else 0.0
    return {"n": n, "win_pct": round(win_pct, 1), "net_rs": round(net_rs, 2),
            "max_dd_rs": round(max_dd_rs, 2), "sqn": round(sqn, 2)}


# ======================================================================
# Self-checks (synthetic data, no network needed)
# ======================================================================

def run_self_checks():
    print("Running sirius_5yr_compounding self-checks (synthetic data)...")

    assert compute_lot_multiplier(25_000) == 1
    assert compute_lot_multiplier(49_999) == 1
    assert compute_lot_multiplier(50_000) == 2
    assert compute_lot_multiplier(124_999) == 4
    assert compute_lot_multiplier(0) == 0
    assert compute_lot_multiplier(-500) == 0
    print("  compute_lot_multiplier: floors correctly, never below 1x while solvent")

    # --- a clean winning sequence must step up lot size as capital crosses each multiple ---
    synth = pd.DataFrame([
        {"date": "2025-01-06", "entry_time": "2025-01-06 09:20:00", "pnl_pts": 500.0},  # big win to cross 2x
        {"date": "2025-01-07", "entry_time": "2025-01-07 09:20:00", "pnl_pts": 5.0},
    ])
    out = simulate_compounding(synth, starting_capital=25_000)
    lot0 = om.lot_size_for_date(pd.to_datetime("2025-01-06").date())
    assert out.iloc[0]["lots"] == lot0, "first trade must use the base 1x lot size"
    assert out.iloc[1]["lots"] > lot0, "after a big enough win, the next trade must size up"
    print("  simulate_compounding: lot size steps up after crossing a capital multiple")

    # --- a wipeout must stop all further trading, not go negative forever ---
    synth_wipe = pd.DataFrame([
        {"date": "2025-01-06", "entry_time": "2025-01-06 09:20:00", "pnl_pts": -1000.0},
        {"date": "2025-01-07", "entry_time": "2025-01-07 09:20:00", "pnl_pts": 500.0},
    ])
    out2 = simulate_compounding(synth_wipe, starting_capital=25_000)
    assert out2.iloc[0]["capital_after_compounded"] <= 0
    assert bool(out2.iloc[1]["skipped_wiped_out"]) is True, "no further trades once the account is wiped out"
    print("  simulate_compounding: wipeout halts further trading correctly")

    # --- capped compounding must never exceed the cap, however much capital grows ---
    assert compute_lot_multiplier(10_000_000, 25_000, max_multiplier=20) == 20
    assert compute_lot_multiplier(30_000, 25_000, max_multiplier=20) == 1
    print("  compute_lot_multiplier: cap is respected even at extreme capital levels")

    # --- 6-month step-up: pure function of elapsed time, not P&L ---
    import datetime as _dt
    start = _dt.date(2021, 8, 6)
    assert compute_stepup_multiplier(start, start) == 1
    assert compute_stepup_multiplier(start + _dt.timedelta(days=181), start) == 1, "not yet 6 months -- still 1x"
    assert compute_stepup_multiplier(start + _dt.timedelta(days=182), start) == 2, "exactly 6 months -- steps to 2x"
    assert compute_stepup_multiplier(start + _dt.timedelta(days=365), start) == 3, "~12 months -- 3x"
    assert compute_stepup_multiplier(start + _dt.timedelta(days=1825), start) == 11, "5 years / 10 half-years -- 11x"
    print("  compute_stepup_multiplier: steps up purely on elapsed time, matches expected schedule")

    print("All sirius_5yr_compounding self-checks passed.\n")


def main():
    run_self_checks()

    print("=" * 78)
    print("SIRIUS 5-YEAR BACKTEST -- WITH COMPOUNDING POSITION SIZING")
    print(f"Using the real trade sequence already saved in {TRADES_CSV}")
    print("=" * 78)

    trades = pd.read_csv(TRADES_CSV, parse_dates=["entry_time", "exit_time"])
    print(f"Loaded {len(trades)} real trades from {trades['date'].min()} to {trades['date'].max()}.\n")

    original_metrics = compute_metrics_from_series(trades["rupee_pnl"], STARTING_CAPITAL)
    print(f"ORIGINAL (fixed 1-lot every trade)      : n={original_metrics['n']:4d}  win={original_metrics['win_pct']}%  "
          f"net=Rs{original_metrics['net_rs']:,.0f}  maxDD=Rs{original_metrics['max_dd_rs']:,.0f}  "
          f"SQN={original_metrics['sqn']}  final=Rs{STARTING_CAPITAL + original_metrics['net_rs']:,.0f}")

    capped = simulate_compounding(trades, STARTING_CAPITAL, max_multiplier=MAX_LOT_MULTIPLIER)
    capped_metrics = compute_metrics_from_series(capped["rupee_pnl_compounded"], STARTING_CAPITAL)
    print(f"COMPOUNDING, capped at {MAX_LOT_MULTIPLIER}x          : n={capped_metrics['n']:4d}  win={capped_metrics['win_pct']}%  "
          f"net=Rs{capped_metrics['net_rs']:,.0f}  maxDD=Rs{capped_metrics['max_dd_rs']:,.0f}  "
          f"SQN={capped_metrics['sqn']}  final=Rs{STARTING_CAPITAL + capped_metrics['net_rs']:,.0f}")

    stepup = simulate_stepup(trades, STARTING_CAPITAL, STEP_UP_EVERY_DAYS)
    stepup_metrics = compute_metrics_from_series(stepup["rupee_pnl_stepup"], STARTING_CAPITAL)
    print(f"+1 LOT EVERY 6 MONTHS (time-based, not P&L) : n={stepup_metrics['n']:4d}  win={stepup_metrics['win_pct']}%  "
          f"net=Rs{stepup_metrics['net_rs']:,.0f}  maxDD=Rs{stepup_metrics['max_dd_rs']:,.0f}  "
          f"SQN={stepup_metrics['sqn']}  final=Rs{STARTING_CAPITAL + stepup_metrics['net_rs']:,.0f}")

    for label, df, col in [("Capped compounding", capped, "skipped_wiped_out"),
                            ("6-month step-up", stepup, "skipped_wiped_out")]:
        if df[col].any():
            wipe_date = df[df[col]].iloc[0]["date"]
            print(f"\n  WARNING ({label}): went bankrupt -- capital hit zero around {wipe_date}, "
                  f"trades after that were skipped, not simulated as if capital were unlimited.")

    print(f"\n  Lot-size growth over time -- capped compounding (max {MAX_LOT_MULTIPLIER}x) vs 6-month step-up "
          f"(sampled every ~200 trades):")
    for i in range(0, len(trades), 200):
        c_row, s_row = capped.iloc[i], stepup.iloc[i]
        print(f"    trade #{i:4d} ({c_row['date']}): capped lots={c_row['lots']:>6}  "
              f"(capital=Rs{c_row['capital_after_compounded']:,.0f})   |   "
              f"step-up lots={s_row['lots']:>4}  (capital=Rs{s_row['capital_after_stepup']:,.0f})")

    capped.to_csv("sirius_5yr_compounding_capped_trades.csv", index=False)
    stepup.to_csv("sirius_5yr_stepup_trades.csv", index=False)
    print("\nSaved: sirius_5yr_compounding_capped_trades.csv / sirius_5yr_stepup_trades.csv")


if __name__ == "__main__":
    main()
